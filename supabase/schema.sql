create table if not exists products (
    id bigint generated by default as identity primary key,
    name text,
    category text,
    cost numeric,
    price numeric,
    stock integer
);

create table if not exists sales (
    id bigint generated by default as identity primary key,
    date timestamptz default now(),
    total numeric,
    total_cost numeric,
    profit numeric,
    payment_method text
);

create table if not exists sale_items (
    id bigint generated by default as identity primary key,
    sale_id bigint references sales(id) on delete cascade,
    product_id bigint references products(id),
    quantity integer,
    price_at_sale numeric,
    cost_at_sale numeric
);

-- Registrar venta de forma atómica (transacción)
create or replace function register_sale(
    p_total numeric, p_total_cost numeric, p_profit numeric,
    p_payment_method text, p_items jsonb
) returns bigint language plpgsql as $$
declare
    v_sale_id bigint;
    item jsonb;
begin
    insert into sales (total, total_cost, profit, payment_method)
    values (p_total, p_total_cost, p_profit, p_payment_method)
    returning id into v_sale_id;

    for item in select * from jsonb_array_elements(p_items) loop
        insert into sale_items (sale_id, product_id, quantity, price_at_sale, cost_at_sale)
        values (v_sale_id, (item->>'product_id')::bigint, (item->>'quantity')::int,
                (item->>'price')::numeric, (item->>'cost')::numeric);
        update products set stock = stock - (item->>'quantity')::int
        where id = (item->>'product_id')::bigint;
    end loop;
    return v_sale_id;
end $$;

-- Seguridad: lectura pública (necesaria para Realtime en el navegador).
-- Las escrituras las hace el servidor con la service_role key.
alter table products enable row level security;
alter table sales enable row level security;
alter table sale_items enable row level security;
create policy "read products" on products for select using (true);
create policy "read sales" on sales for select using (true);
create policy "read sale_items" on sale_items for select using (true);

-- Activar Realtime
alter publication supabase_realtime add table products, sales, sale_items;

